// ISR Stub Generation — 256 Interrupt Service Routines
//
// Phase 1.3: Each ISR stub pushes its vector number and jumps to
// a common handler that saves GPRs and dispatches to C++.
//
// Approach: C preprocessor macros generate 256 stub functions.
// Each stub is ~11 bytes (push imm8 + jmp rel32).
// No external assembler (NASM/YASM) required — pure Clang.
//
// Intel SDM Vol.3A §6.12 — Stack state on exception entry

