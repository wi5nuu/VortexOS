// ─── Common Handler (assembly) ──────────────────────────────────────────────
// Saves all GPRs, calls C++ isr_dispatch, restores GPRs, returns via IRETQ.
//
// Stack on entry (from ISR stub):
//   [CPU]: SS, RSP, RFLAGS, CS, RIP, [error_code]
//   [stub]: vector_number
//
// After pusha-equivalent, RSP points to InterruptFrame (idt.hpp).

// The common handler and dispatch entry point
asm(
    ".text\n"
    ".globl isr_common_handler\n"
    ".type isr_common_handler, @function\n"
    "isr_common_handler:\n"
    // Save all GPRs (pushaq equivalent)
    "  pushq %rax\n"
    "  pushq %rbx\n"
    "  pushq %rcx\n"
    "  pushq %rdx\n"
    "  pushq %rsi\n"
    "  pushq %rdi\n"
    "  pushq %rbp\n"
    "  pushq %r8\n"
    "  pushq %r9\n"
    "  pushq %r10\n"
    "  pushq %r11\n"
    "  pushq %r12\n"
    "  pushq %r13\n"
    "  pushq %r14\n"
    "  pushq %r15\n"
    // Call C++ dispatch: isr_dispatch(InterruptFrame* frame)
    // RDI = pointer to stack frame (System V AMD64 ABI)
    "  movq %rsp, %rdi\n"
    "  callq isr_dispatch\n"
    // Restore all GPRs (popaq equivalent)
    "  popq %r15\n"
    "  popq %r14\n"
    "  popq %r13\n"
    "  popq %r12\n"
    "  popq %r11\n"
    "  popq %r10\n"
    "  popq %r9\n"
    "  popq %r8\n"
    "  popq %rbp\n"
    "  popq %rdi\n"
    "  popq %rsi\n"
    "  popq %rdx\n"
    "  popq %rcx\n"
    "  popq %rbx\n"
    "  popq %rax\n"
    // Remove vector number from stack (+8)
    "  addq $8, %rsp\n"
    // Return from interrupt — CPU restores CS:RIP, SS:RSP, RFLAGS
    "  iretq\n"
);

// ─── ISR Stub Macro ─────────────────────────────────────────────────────────
// Each stub pushes its vector number and jumps to the common handler.
// The stub is small (~11 bytes): pushq $imm8 (2 bytes) + jmp rel32 (5 bytes).
#define DEFINE_ISR_STUB(n) \
    extern "C" void isr_stub_##n(); \
    asm( \
        ".text\n" \
        ".globl isr_stub_" #n "\n" \
        ".type isr_stub_" #n ", @function\n" \
        "isr_stub_" #n ":\n" \
        "  pushq $" #n "\n" \
        "  jmp isr_common_handler\n" \
    );

