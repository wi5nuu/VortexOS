// ─── Pixel Operations ─────────────────────────────────────────────────────────

static inline void put_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= kFbWidth || y >= kFbHeight) return;

    uint32_t bytes_per_pixel = kFbBpp / 8;
    volatile uint8_t* ptr = kFbBase + y * kFbPitch + x * bytes_per_pixel;

    ptr[0] = static_cast<uint8_t>(color);
    ptr[1] = static_cast<uint8_t>(color >> 8);
    ptr[2] = static_cast<uint8_t>(color >> 16);
}

// ─── Public API ───────────────────────────────────────────────────────────────

